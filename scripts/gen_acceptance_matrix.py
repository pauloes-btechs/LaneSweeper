"""Build docs/ACCEPTANCE_MATRIX.md from JUnit XML of an actual test run (never hand-edited pass marks).

Usage: python scripts/gen_acceptance_matrix.py /tmp/junit/*.xml [--e2e "step|step|..."] [--date YYYY-MM-DD]
"""
import argparse
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

AREAS = [  # (substring of classname/file, area)
    ("security.test_rls", "Tenancy & RLS"), ("security.test_approval_ledger", "Approval ledger"),
    ("integration.test_sql_functions", "SQL functions (geo, jobs, search)"), ("test_policy", "Policy engine & permissions"),
    ("test_models", "Model router, budgets, kill switch, parsers"), ("test_ticket_graph", "Ticket graph & scenarios"),
    ("test_fleet_graph", "Fleet graph (nightly planning)"), ("test_glasses", "Glasses graph & device link"),
    ("test_copilot_tools", "Copilot & typed tools"), ("test_api", "HTTP API"),
    ("test_jobs", "Job runner"), ("test_sim", "Simulator & safety controller"),
]
VITEST = {"glasses": "packages/glasses", "console": "apps/console", "site": "apps/site (original)"}

REQS = [  # (requirement from the build prompt, [test names that must have passed])
    ("Physical side effects impossible, even for admins", ["test_physical_side_effect_always_denied_even_for_admins", "test_mission_on_real_robot_is_impossible"]),
    ("Real dispatch cannot even be requested", ["test_real_dispatch_cannot_even_be_requested"]),
    ("Approval bound to exact payload; single use", ["test_approval_payload_is_immutable", "test_one_approval_cannot_start_two_missions"]),
    ("Separation of duties", ["test_requester_cannot_self_approve_fleet_plan"]),
    ("Revocation during interrupt blocks resume (Scenario H)", ["test_revocation_between_interrupt_and_resume_blocks_dispatch"]),
    ("Interrupt survives a process restart", ["test_interrupt_survives_process_restart"]),
    ("Forged JWT roles/tenants grant nothing", ["test_forged_role_and_tenant_claims_grant_nothing", "test_staff_routes_require_auth_and_ignore_forged_claims"]),
    ("Cross-tenant evidence denied", ["test_cross_tenant_ticket_access_is_404_and_jurisdiction_param_checked"]),
    ("Cleared requires after-evidence (Scenario F)", ["test_ticket_cannot_be_verified_closed_without_cleared_verdict"]),
    ("Model output cannot become motion commands", ["test_vision_parser_keeps_observations_and_discards_motion_fields"]),
    ("Prompt injection cannot dispatch", ["test_injected_plan_cannot_dispatch_or_assign"]),
    ("Billable kill switch", ["test_kill_switch_db_flag_blocks_live_calls"]),
    ("Lost link → pause → supervisor resume, no duplicate work (Scenario G)", ["test_scenario_g_lost_link_pauses_then_supervisor_resumes_without_duplicate_work", "test_console_safety_resume_path_over_http"]),
    ("Cyclist → local yield → auto resume (Scenario E)", ["test_scenario_e_cyclist_causes_local_yield_and_auto_resume"]),
    ("Optical false positive never claimed cleared", ["test_optical_false_positive_is_marked_unverified"]),
    ("Device requests signed; tampering rejected", ["test_device_signature_roundtrip_and_tamper", "test_signed_device_event_flow"]),
    ("Image minimisation strips EXIF and crops", ["test_minimise_frame_crops_road_band_and_strips_exif"]),
    ("Audit log append-only", ["test_audit_log_is_append_only"]),
]


def area(cls: str, file: str) -> str:
    key = f"{cls} {file}"
    return next((a for k, a in AREAS if k in key), cls or file)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("xml", nargs="+")
    ap.add_argument("--e2e", default="")
    ap.add_argument("--date", required=True)
    a = ap.parse_args()
    rows: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for f in a.xml:
        for tc in ET.parse(f).getroot().iter("testcase"):
            st = "fail" if tc.find("failure") is not None or tc.find("error") is not None else "skip" if tc.find("skipped") is not None else "pass"
            stem = Path(f).stem
            label = f"{VITEST[stem]}: {tc.get('classname')}" if stem in VITEST else area(tc.get("classname", ""), tc.get("file", ""))
            rows[label].append((tc.get("name"), st))
    total = sum(len(v) for v in rows.values())
    passed = sum(s == "pass" for v in rows.values() for _, s in v)
    out = [f"# Acceptance matrix ({a.date})", "",
           "Generated by `scripts/gen_acceptance_matrix.py` from JUnit output of a run made in this build session. Only tests that",
           "actually ran are listed. Anything not run here is under *Not verified here*.", "",
           f"**{passed}/{total} automated tests passed** (offline mode, `BILLABLE_CALLS_ENABLED=false`).", "",
           "| Area | Tests | Passed |", "|---|---|---|"]
    out += [f"| {k} | {len(v)} | {sum(s == 'pass' for _, s in v)} |" for k, v in sorted(rows.items())]
    status = {n: st for v in rows.values() for n, st in v}
    out += ["", "## Key requirements → proving tests", "", "| Requirement | Tests | Result |", "|---|---|---|"]
    for req, names in REQS:
        res = [status.get(n, "not run") for n in names]
        mark = "✓ passed" if all(r == "pass" for r in res) else "✗ " + ", ".join(f"{n}: {r}" for n, r in zip(names, res) if r != "pass")
        out.append(f"| {req} | " + "<br>".join(f"`{n}`" for n in names) + f" | {mark} |")
    if a.e2e:
        steps = a.e2e.split("|")
        out += ["", f"## Browser E2E (Chrome, real API + built console): {len(steps)}/{len(steps)} steps passed", ""]
        out += [f"- ✓ {s}" for s in steps]
    out += ["", "## Test inventory", ""]
    for k, v in sorted(rows.items()):
        out += [f"<details><summary>{k} ({len(v)})</summary>", ""] + [f"- {'✓' if s == 'pass' else '✗ ' + s} `{n}`" for n, s in v] + ["", "</details>"]
    out += ["", "## Not verified here", "",
            "- Supabase Edge Function Deno tests: run in CI (`edge-functions.yml`), Deno is not installed in this build environment.",
            "- Live Gemini calls: the live code paths are mock-tested only; `lanekeeper models-verify` has not been run with a real key.",
            "- Any physical hardware: no robot or Microlumin glasses exist for this project; all such behaviour is simulated.",
            "- The hosted Supabase project (paused); all database tests ran against local Postgres 16 + PostGIS + pgvector."]
    Path(__file__).resolve().parents[1].joinpath("docs/ACCEPTANCE_MATRIX.md").write_text("\n".join(out) + "\n")
    print(f"{passed}/{total}")


if __name__ == "__main__":
    main()
